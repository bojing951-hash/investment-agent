def f(x, n=4, sign=False):
    if x is None:
        return 'NA'
    return ('%+.*f' % (n, x)) if sign else ('%.*f' % (n, x))


def cand_s(V):
    c = V.get('cand') or {}
    return '%s/%s/%s/%s' % (c.get('scanned'), c.get('valid'), c.get('dropped_overlap'), c.get('dropped_insufficient'))


def six_steps(EX):
    d = EX.get('jp_diffs_bp') or {}
