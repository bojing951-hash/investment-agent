def paths_of(sub):
    res = []

    def walk(o, p):
        if isinstance(o, dict):
            for k, v in o.items():
                walk(v, p + "." + k)
        elif isinstance(o, list):
            for i, v in enumerate(o):
                walk(v, "%s[%d]" % (p, i))
        elif isinstance(o, str) and sub in o:
            res.append(p)
    walk(aj, "$")
    return res


def item(sev, label, note, orig, fix, extra=()):
    assert orig in open(aj_p, encoding="utf-8").read(), "原句未在受审稿中找到: " + orig
    ps = list(paths_of(orig))
    for e in extra:
        assert paths_of(e), "原句未在受审稿中找到: " + e
        ps += paths_of(e)
    return {"severity": sev, "where": "agent_judgment.json " + label + " — " + "; ".join(dict.fromkeys(ps)),
            "note": note, "original": orig, "fix": fix}


